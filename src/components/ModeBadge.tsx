"use client";
import Link from "next/link";
import { Sparkles, BookOpen } from "lucide-react";
import { useHealth } from "@/lib/client/health";

export function ModeBadge() {
  const h = useHealth();
  if (!h) return <span className="skeleton h-7 w-28 rounded-full" aria-hidden />;
  const live = h.mode === "live";
  return (
    <Link
      href="/about#modes"
      className={
        "inline-flex items-center gap-1.5 rounded-full border px-3 py-1 text-xs font-medium " +
        (live ? "border-accent/30 bg-accent-soft text-accent-strong" : "border-warn/30 bg-warn-soft text-warn")
      }
      title={live ? `Live AI generation with ${h.model}` : "Educational demo mode: preapproved content, not live AI"}
    >
      {live ? <Sparkles size={14} aria-hidden /> : <BookOpen size={14} aria-hidden />}
      <span>{live ? "Live AI" : "Demo mode"}</span>
      <span className="sr-only">{live ? `: answers are generated by ${h.model} and checked before display` : ": preapproved educational content, not live AI generation"}</span>
    </Link>
  );
}
