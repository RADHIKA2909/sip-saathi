import { CheckCircle2, ShieldCheck, ShieldAlert, XCircle, Info } from "lucide-react";
import { FALLBACK_REASON_LABEL, type CheckResult, type InputFlag, type JudgeReport, type ResponseMode, type FallbackReason } from "@/lib/types";
import { Badge } from "./ui";

export function ModeLabel({ mode, demoReason }: { mode: ResponseMode; demoReason?: string }) {
  if (mode === "live") return <Badge tone="accent">Live AI · validated</Badge>;
  if (mode === "demo")
    return <Badge tone="warn">{demoReason === "forced_demo" ? "Educational demo mode (forced)" : "Educational demo mode: preapproved content, not live AI"}</Badge>;
  return <Badge tone="info">Safe preapproved response</Badge>;
}

export function SafetyPanel({
  mode, checks, inputFlags, judge, fallbackReason, masked, model, versions, latencyMs, cachedAt, classifier, defaultOpen = false,
}: {
  mode: ResponseMode;
  checks: CheckResult[];
  inputFlags: InputFlag[];
  judge?: JudgeReport;
  fallbackReason?: FallbackReason;
  masked: boolean;
  model?: string;
  versions: { prompt: string; kb: string; policy: string };
  latencyMs: number;
  cachedAt?: string;
  classifier?: { deterministic: string; ai?: string; agreed?: boolean; alternatives: string[] };
  defaultOpen?: boolean;
}) {
  const failed = checks.filter((c) => !c.passed);
  return (
    <details className="rounded-xl border border-border bg-surface-2/60" open={defaultOpen}>
      <summary className="flex cursor-pointer list-none items-center gap-2 p-3.5 text-sm font-semibold [&::-webkit-details-marker]:hidden">
        {fallbackReason ? <ShieldAlert size={18} className="text-info" aria-hidden /> : <ShieldCheck size={18} className="text-accent-strong" aria-hidden />}
        What was checked
        <span className="ml-auto text-xs font-normal text-muted">
          {checks.length - failed.length}/{checks.length} checks passed{fallbackReason ? " · fallback shown" : ""}
        </span>
      </summary>
      <div className="space-y-4 border-t border-border p-3.5 text-sm">
        <ol className="space-y-3" aria-label="Safety pipeline steps">
          <Step n={1} title="Input screen">
            {inputFlags.length ? (
              <ul className="mt-1 flex flex-wrap gap-1.5">
                {inputFlags.map((f) => (
                  <li key={f.id}><Badge tone={["distress", "prompt_injection", "fund_recommendation", "return_prediction"].includes(f.id) ? "warn" : "neutral"}>{f.label}</Badge></li>
                ))}
              </ul>
            ) : (
              <p className="text-muted">No safety flags raised.</p>
            )}
            {masked && <p className="mt-1 text-muted">Personal identifiers were replaced with placeholders before anything was processed or stored.</p>}
          </Step>
          {classifier && (
            <Step n={2} title="Concern classification">
              <p className="text-muted">
                Rule-based: <span className="text-foreground">{classifier.deterministic.replace(/_/g, " ")}</span>
                {classifier.ai && <> · AI: <span className="text-foreground">{classifier.ai.replace(/_/g, " ")}</span> {classifier.agreed ? "(agree)" : "(disagree)"}</>}
              </p>
            </Step>
          )}
          <Step n={3} title={mode === "live" ? "Generation" : "Response source"}>
            <p className="text-muted">
              {mode === "live" && <>Generated by {model}{cachedAt ? ` (cached scenario answer from ${new Date(cachedAt).toLocaleString("en-IN")})` : ""}, using only retrieved knowledge-base passages.</>}
              {mode === "demo" && <>Preapproved educational content selected by rules. No AI model was called.</>}
              {mode === "fallback" && fallbackReason && <>Preapproved response shown because: {FALLBACK_REASON_LABEL[fallbackReason].toLowerCase()}.</>}
            </p>
          </Step>
          <Step n={4} title="Output validation">
            <ul className="mt-1 space-y-1">
              {checks.map((c) => (
                <li key={c.id} className="flex gap-2">
                  {c.passed ? <CheckCircle2 size={16} className="mt-0.5 shrink-0 text-accent-strong" aria-label="passed" /> : <XCircle size={16} className="mt-0.5 shrink-0 text-danger" aria-label="failed" />}
                  <span>
                    {c.label}
                    {c.detail && <span className="block text-xs text-muted">{c.detail}</span>}
                  </span>
                </li>
              ))}
            </ul>
            {mode === "fallback" && failed.length > 0 && <p className="mt-2 text-xs text-muted">The failing draft was not shown. The checks above refer to that draft; the preapproved response displayed instead passes every rule.</p>}
          </Step>
          {judge && (judge.ran || judge.error) && (
            <Step n={5} title="AI quality judge (fallible automated estimate)">
              {judge.ran ? (
                <p className="text-muted">
                  Verdict: <span className="text-foreground">{judge.verdict}</span> · grounded: {String(judge.grounded)} · advice risk: {judge.adviceRisk}
                  {judge.issues?.length ? <span className="block text-xs">Issues: {judge.issues.join("; ")}</span> : null}
                </p>
              ) : (
                <p className="text-muted">Judge unavailable ({judge.error}); deterministic checks still applied.</p>
              )}
            </Step>
          )}
        </ol>
        <p className="flex items-start gap-1.5 text-xs text-muted">
          <Info size={14} className="mt-0.5 shrink-0" aria-hidden />
          {versions.prompt} · {versions.kb} · {versions.policy} · {latencyMs} ms. Automated checks reduce risk but cannot guarantee every answer is correct.
        </p>
      </div>
    </details>
  );
}

function Step({ n, title, children }: { n: number; title: string; children: React.ReactNode }) {
  return (
    <li className="flex gap-3">
      <span className="grid h-6 w-6 shrink-0 place-items-center rounded-full bg-surface text-xs font-semibold text-muted ring-1 ring-border" aria-hidden>{n}</span>
      <div className="min-w-0 flex-1">
        <p className="font-medium">{title}</p>
        {children}
      </div>
    </li>
  );
}
